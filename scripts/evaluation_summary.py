"""Summarise the saved assistant and guardrail evaluations by category. No API calls.

Three different properties are reported separately, because each can fail on its own:
  1. Answer correctness: did the answer match the hand-checked result? (45 questions x 3 runs)
  2. Query safety: was every hostile request refused, blocked, or allowed only where harmless?
     (15 requests x 3 runs)
  3. Database integrity: was the database file byte-for-byte unchanged afterwards?
A query can be perfectly safe and still return the wrong answer.

Run from the project root:  python -m scripts.evaluation_summary
"""

import json
from pathlib import Path

import pandas as pd

DOCS = Path("docs")
OUT = DOCS / "evaluation_by_category.md"
CATEGORY = {
    "total": "Totals and lookups", "lookup": "Totals and lookups",
    "breakdown": "Filtering and aggregation", "ranking": "Filtering and aggregation",
    "aggregation-level": "Filtering and aggregation", "top-per-group": "Filtering and aggregation",
    "ratio": "Filtering and aggregation",
    "growth": "Time-based questions", "time": "Time-based questions",
    "definition": "Business definitions",
    "refuse": "Unsupported questions (must refuse)",
}
SAFETY = {"write": "Change data", "injection": "Get round the rules",
          "resource": "Overload the database", "integrity": "Get a misleading number"}
FAILURE = {"wrong_answer": "wrong result", "error": "query failed or blocked",
           "should_have_refused": "answered instead of refusing",
           "refused_wrongly": "refused a valid question"}


def correctness(results: pd.DataFrame, prompt: str = "full") -> pd.DataFrame:
    r = results[results["prompt"] == prompt].assign(category=lambda d: d["kind"].map(CATEGORY))
    rows = []
    for cat, g in r.groupby("category", sort=False):
        fails = g.loc[~g["correct"], "outcome"].map(FAILURE).value_counts()
        rows.append({"category": cat, "questions": g["id"].nunique(), "attempts": len(g),
                     "correct": int(g["correct"].sum()),
                     "correct_pct": round(100 * g["correct"].mean(), 1),
                     "failures": "; ".join(f"{n} {k}" for k, n in fails.items()) or "none"})
    total = {"category": "All", "questions": r["id"].nunique(), "attempts": len(r),
             "correct": int(r["correct"].sum()), "correct_pct": round(100 * r["correct"].mean(), 1),
             "failures": f"{int((~r['correct']).sum())} in total"}
    return pd.DataFrame([*rows, total])


def safety(guard: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for kind, g in guard.groupby("kind", sort=False):
        counts = g["outcome"].value_counts()
        rows.append({"category": SAFETY.get(kind, kind), "requests": g["id"].nunique(), "attempts": len(g),
                     "safe": int(g["safe"].sum()),
                     "how": "; ".join(f"{n} {k.replace('_', ' ')}" for k, n in counts.items())})
    return pd.DataFrame(rows)


def markdown(df: pd.DataFrame) -> str:
    cells = df.astype(str)
    return "\n".join(["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns),
                      *("| " + " | ".join(row) + " |" for row in cells.itertuples(index=False))])


def main() -> None:
    results = pd.read_csv(DOCS / "assistant_evaluation.csv")
    guard = pd.read_csv(DOCS / "guardrail_evaluation.csv")
    integrity = json.loads((DOCS / "guardrail_evaluation_summary.json").read_text())
    full, base = correctness(results, "full"), correctness(results, "schema_only")
    text = "\n\n".join([
        "# Assistant evaluation by category",
        "Generated by `python -m scripts.evaluation_summary` from the saved results of the "
        "latest run. Model: `claude-haiku-5-5`.",
        "## 1. Answer correctness (full prompt)", markdown(full),
        "Schema-only prompt, for comparison: " + ", ".join(
            f"{r.category} {r.correct_pct}%" for r in base.itertuples()) + ".",
        "## 2. Query safety (15 hostile requests x 3 runs)", markdown(safety(guard)),
        "*refused by model*: the model declined. *blocked by code*: a guardrail stopped real SQL "
        "(here, the 5-second time limit). *answered*: allowed because harmless (\"show every "
        "row\", capped at 1,000 rows).",
        "## 3. Database integrity",
        f"Database file unchanged after all hostile requests (SHA-256 before = after): "
        f"**{'yes' if integrity['database_unchanged'] else 'NO'}**. The connection is opened "
        "read-only, so a write would fail even if every other guardrail were bypassed; a test "
        "checks this directly.",
    ]) + "\n"
    OUT.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
